"""Interface language / язык интерфейса: Russian (ru, default) or English (en).

Priority / приоритет: CLI --lang  >  KONVEYER_LANG env  >  [ui] lang in konveyer.toml  >  "ru".
Russian is the source language of all messages; English is looked up here.
Only the *interface* changes (help, logs, errors, web UI). Pipeline behaviour
(translation target, voiceover language, post language) is not affected.
"""
from __future__ import annotations

import os
import re

LANGS = ("ru", "en")
_lang: str | None = None


def normalize(value: str | None) -> str:
    v = (value or "").strip().lower()[:2]
    return v if v in LANGS else ""


def set_lang(value: str | None) -> str:
    global _lang
    _lang = normalize(value) or "ru"
    os.environ["KONVEYER_LANG"] = _lang      # child processes / web server inherit it
    return _lang


def get_lang() -> str:
    if _lang:
        return _lang
    return normalize(os.environ.get("KONVEYER_LANG")) or "ru"


def init_from_settings(settings) -> str:
    """Use [ui] lang only if nothing more explicit was chosen."""
    if _lang or normalize(os.environ.get("KONVEYER_LANG")):
        return get_lang()
    ui = getattr(settings, "ui", None)
    return set_lang(getattr(ui, "lang", "ru"))


