_CYR = re.compile(r"[А-Яа-яЁё]")
_frag_cache: list[tuple[re.Pattern, str]] | None = None


def _fragments() -> list[tuple[re.Pattern, str]]:
    global _frag_cache
    if _frag_cache is None:
        items = {**_WORDS, **{k: v for k, v in _EN.items() if len(k.strip()) >= 3}}
        out = []
        for ru in sorted(items, key=len, reverse=True):
            if not _CYR.search(ru):
                continue
            pat = re.escape(ru)
            if _CYR.match(ru[0]):
                pat = r"(?<![А-Яа-яЁё])" + pat
            if _CYR.match(ru[-1]):
                pat = pat + r"(?![А-Яа-яЁё])"
            out.append((re.compile(pat), items[ru]))
        _frag_cache = out
    return _frag_cache


_UNITS = [(re.compile(r"(\d) с(?![А-Яа-яЁё])"), r"\1 s"), (re.compile(r"(\d) МБ"), r"\1 MB"),
          (re.compile(r"(\d) мин(?![А-Яа-яЁё])"), r"\1 min")]


def tr(text, lang: str | None = None):
    """Translate an interface string from Russian into the current language."""
    if not isinstance(text, str) or (lang or get_lang()) != "en" or not _CYR.search(text):
        return text
    if text in _EN:
        return _EN[text]
    stripped = text.strip()
    if stripped in _EN:
        return text.replace(stripped, _EN[stripped])
    out = text
    for pat, en in _fragments():
        if not _CYR.search(out):
            break
        out = pat.sub(lambda m, en=en: en, out)
    for pat, rep in _UNITS:
        out = pat.sub(rep, out)
    return out


def translate_parser(parser) -> None:
    """Translate argparse help, descriptions and group titles in place."""
    if get_lang() != "en":
        return
    import argparse

    seen = set()

    def walk(p):
        if id(p) in seen:
            return
        seen.add(id(p))
        p.description = tr(p.description)
        for g in getattr(p, "_action_groups", []):
            g.title = tr(g.title)
            g.description = tr(g.description)
        for act in p._actions:
            if act.help and act.help is not argparse.SUPPRESS:
                act.help = tr(act.help)
            if isinstance(act.metavar, str):
                act.metavar = _METAVARS.get(act.metavar, act.metavar)
            if isinstance(act, argparse._SubParsersAction):
                for ch in act._choices_actions:
                    ch.help = tr(ch.help)
                for sub in act.choices.values():
                    walk(sub)

    walk(parser)


